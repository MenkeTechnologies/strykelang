//! `--compat` must let a user `sub` win over a stryke **extension** builtin of the
//! same name, while leaving Perl 5 **core** operators alone.
//!
//! `--compat` is documented as "disable all stryke extensions", so plain Perl that
//! defines `sub all { … }` and calls `all()` has to reach its own sub. Before the
//! `Compiler::compat_user_sub_wins` guard, the compiler's `FuncCall` dispatch table
//! lowered these names straight to `Op::CallBuiltin`, which `patch_static_sub_calls`
//! never revisits — so the user's sub was unreachable.
//!
//! `tests/suite/cli_compat_mode.rs` already pins this for `collect`, but that name
//! takes a dispatch arm that emits `Op::Call`, so it never exercised the
//! `Op::CallBuiltin` arms. These cases do.
//!
//! The core/extension split is the `CORE_CATEGORY_MAP` / `EXT_CATEGORY_MAP`
//! partition generated by `build.rs`, surfaced as `builtins::is_perl5_core_name`.
//! Every expectation below is stock `perl` behavior.

use std::process::Command;

/// Run `st --compat -e PROG` and return trimmed stdout, asserting the run succeeded.
fn compat_eval(prog: &str) -> String {
    let exe = env!("CARGO_BIN_EXE_st");
    let out = Command::new(exe)
        .args(["--compat", "-e", prog])
        .output()
        .expect("spawn stryke");
    assert!(
        out.status.success(),
        "`{prog}` failed under --compat\nstdout: {}\nstderr: {}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr),
    );
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}

#[test]
fn compat_user_sub_beats_extension_builtin() {
    // `all` / `any` / `none` / `first` are stryke list extensions, not Perl core, so
    // a same-named user sub owns the bare call. Stock perl prints the sub's value.
    assert_eq!(compat_eval("sub all { 42 } print all();"), "42");
    assert_eq!(compat_eval("sub any { 7 } print any();"), "7");
    assert_eq!(compat_eval("sub none { 'n' } print none();"), "n");
}

#[test]
fn compat_user_sub_receives_its_arguments() {
    // The redirect must go through the normal user-sub calling convention, so `@_`
    // is populated exactly as a plain call would populate it.
    assert_eq!(
        compat_eval("sub all { return join('-', @_) } print all(1, 2, 3);"),
        "1-2-3"
    );
}

#[test]
fn compat_perl_core_builtin_still_wins() {
    // Perl itself does NOT let a plain `sub length { … }` override the named
    // operator (that needs `use subs` / `CORE::GLOBAL`), so `--compat` must not
    // either. Both of these print the builtin's answer under stock perl.
    assert_eq!(
        compat_eval(r#"sub length { 99 } print length("abcd");"#),
        "4"
    );
    assert_eq!(compat_eval(r#"sub uc { "X" } print uc("ab");"#), "AB");
}

#[test]
fn non_compat_mode_still_rejects_redefining_a_builtin() {
    // The redirect is `--compat`-only: default mode keeps the no-shadow invariant
    // and reports it rather than silently picking one.
    let exe = env!("CARGO_BIN_EXE_st");
    let out = Command::new(exe)
        .args(["-e", "sub all { 42 } print all();"])
        .output()
        .expect("spawn stryke");
    assert!(
        !out.status.success(),
        "default mode must reject redefining a builtin, got: {}",
        String::from_utf8_lossy(&out.stdout)
    );
}
